#!/usr/bin/env python3
"""Generates Gimano's duotone icons for Android from docs/icons/gimano-icons.json.

Outputs
  app/src/main/res/drawable/gi_<name>.xml   VectorDrawables (stroke 2, round caps/joins,
                                            closed sub-paths filled with tint @ 60 %)
  app/src/main/java/my/gimano/app/ui/common/GimanoIconPaths.kt
                                            the same data for Compose (per-context colours)

Run from android/:  python3 tools/gen_icons.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "..", "docs", "icons", "gimano-icons.json")
RES = os.path.join(ROOT, "app", "src", "main", "res", "drawable")
KT = os.path.join(ROOT, "app", "src", "main", "java", "my", "gimano", "app", "ui", "common", "GimanoIconPaths.kt")

TOKEN = re.compile(r"[MmLlHhVvCcSsQqTtAaZz]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?")
ARGS = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6, "S": 4, "Q": 4, "T": 2, "A": 7, "Z": 0}


def split_subpaths(d):
    """Splits path data at moveto commands; returns [(data, closed)]. A sub-path is
    'closed' if it has Z or its end point returns to its start (e.g. circles)."""
    toks = TOKEN.findall(d)
    subs, cur, i = [], [], 0
    cx = cy = sx = sy = 0.0
    cmd = None
    closed = False
    first = True

    def flush():
        nonlocal cur, closed
        if cur:
            end_match = abs(cx - sx) < 1e-3 and abs(cy - sy) < 1e-3
            subs.append((" ".join(cur), closed or end_match))
        cur, closed = [], False

    while i < len(toks):
        t = toks[i]
        if re.match(r"[A-Za-z]", t):
            cmd = t
            i += 1
            if cmd in "Mm":
                flush()
                if first and cmd == "m":
                    cmd = "M"  # leading relative moveto is absolute
            if cmd in "Zz":
                cur.append("Z"); closed = True
                cx, cy = sx, sy
                continue
        n = ARGS[cmd.upper()]
        vals = [float(v) for v in toks[i:i + n]]
        i += n
        rel = cmd.islower()
        up = cmd.upper()
        if up == "M":
            x, y = vals
            if rel and not first: x += cx; y += cy
            cx, cy, sx, sy = x, y, x, y
            cur.append(f"M{fmt(x)},{fmt(y)}")
            cmd = "l" if rel else "L"  # implicit lineto
            first = False
            continue
        first = False
        if up == "H":
            x = vals[0] + (cx if rel else 0); cur.append(f"H{fmt(x)}"); cx = x
        elif up == "V":
            y = vals[0] + (cy if rel else 0); cur.append(f"V{fmt(y)}"); cy = y
        else:
            pts = vals[:]
            if up == "A":
                x, y = pts[5] + (cx if rel else 0), pts[6] + (cy if rel else 0)
                cur.append("A" + ",".join(fmt(v) for v in pts[:5]) + f",{fmt(x)},{fmt(y)}")
            else:
                absv = []
                for k in range(0, len(pts), 2):
                    absv += [pts[k] + (cx if rel else 0), pts[k + 1] + (cy if rel else 0)]
                cur.append(up + ",".join(fmt(v) for v in absv))
                x, y = absv[-2], absv[-1]
            cx, cy = x, y
    flush()
    return subs


def fmt(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def main():
    icons = json.load(open(SRC))["icons"]
    os.makedirs(RES, exist_ok=True)
    kt_entries = []
    for name, d in icons.items():
        subs = split_subpaths(d)
        fill = " ".join(s for s, c in subs if c)
        stroke = " ".join(s for s, _ in subs)
        xml = ['<?xml version="1.0" encoding="utf-8"?>',
               f'<!-- GENERATED by tools/gen_icons.py from docs/icons/gimano-icons.json ("{name}"). Do not edit. -->',
               '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
               '    android:width="24dp" android:height="24dp"',
               '    android:viewportWidth="24" android:viewportHeight="24">']
        if fill:
            xml.append(f'    <path android:fillColor="@color/gi_tint" android:fillAlpha="0.6" android:pathData="{fill}" />')
        xml.append(f'    <path android:fillColor="#00000000" android:strokeColor="@color/gi_ink" android:strokeWidth="2"'
                   f' android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{stroke}" />')
        xml.append('</vector>')
        open(os.path.join(RES, f"gi_{name}.xml"), "w").write("\n".join(xml) + "\n")
        kt_entries.append(f'        "{name}" to IconPath(\n            fill = "{fill}",\n            stroke = "{stroke}",\n        ),')
    kt = f'''// GENERATED by tools/gen_icons.py from docs/icons/gimano-icons.json. Do not edit.
package my.gimano.app.ui.common

/** Gimano Cobalt icon geometry (24-unit grid). [fill] holds only the closed sub-paths. */
data class IconPath(val fill: String, val stroke: String)

object GimanoIconPaths {{
    val all: Map<String, IconPath> = mapOf(
{chr(10).join(kt_entries)}
    )
}}
'''
    open(KT, "w").write(kt)
    print(f"generated {len(icons)} icons")


if __name__ == "__main__":
    main()
