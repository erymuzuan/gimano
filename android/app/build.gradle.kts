require(releaseApiBaseUrl.startsWith("https://")) { "gimano.releaseApiBaseUrl must be https" }

// Release signing: git-ignored android/keystore.properties (see keystore.properties.example).
// The password comes from the macOS Keychain (or GIMANO_KEYSTORE_PASSWORD), never from the repo.
val keystoreProps = Properties().apply {
    rootProject.file("keystore.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
}
val keystorePassword: String? by lazy {
    System.getenv("GIMANO_KEYSTORE_PASSWORD")?.takeIf { it.isNotBlank() }
        ?: keystoreProps.getProperty("storePassword")?.takeIf { it.isNotBlank() }
        ?: keystoreProps.getProperty("keychainService")?.let { svc ->
            runCatching {
                providers.exec {
                    commandLine("security", "find-generic-password", "-a", keystoreProps.getProperty("keychainAccount", "gimano"), "-s", svc, "-w")
                }.standardOutput.asText.get().trim()
            }.getOrNull()
        }
}

// Google Drive backup: OAuth client id lives in git-ignored android/gimano.local.properties
// (see gimano.local.properties.example). Blank → the app shows "Google Drive not configured".
val localProps = Properties().apply {
    listOf("local.properties", "gimano.local.properties").map { rootProject.file(it) }.filter { it.exists() }.forEach { f -> f.inputStream().use { load(it) } }
}
// Play Integrity (votes): Google Cloud project NUMBER, git-ignored. Absent → votes carry no attestation.
val cloudProjectNumber = (localProps.getProperty("gimano.cloudProjectNumber") ?: (project.findProperty("gimano.cloudProjectNumber") as String?) ?: "0").trim().toLongOrNull() ?: 0L
val googleOauthClientId = (localProps.getProperty("gimano.googleAndroidClientId") ?: localProps.getProperty("gimano.googleOauthClientId")
    ?: (project.findProperty("gimano.googleAndroidClientId") as String?) ?: "").trim()

// Debug-only network security config: cleartext HTTP is allowed for the dev hosts below plus
// whatever host gimano.apiBaseUrl points at. Release uses src/main/res/xml (HTTPS only).
val debugCleartextHosts = (listOf("100.101.150.9", "10.0.2.2", "localhost", "127.0.0.1") +
    URI(apiBaseUrl).host).distinct()
val domainLines = debugCleartextHosts.joinToString("\n") { host -> "        <domain includeSubdomains='false'>" + host + "</domain>" }
val generatedDebugRes = layout.buildDirectory.dir("generated/gimano/debugRes").get().asFile
File(generatedDebugRes, "xml").apply { mkdirs() }.resolve("network_security_config.xml").writeText(
    """<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by app/build.gradle.kts for DEBUG builds only. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
$domainLines
    </domain-config>
</network-security-config>
""",
)

